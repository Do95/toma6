  # Precio con el símbolo configurado: $1,250.00 (o $1,250 si no tiene decimales y round: true)
  def money(value, symbol: settings.currency_symbol, round: false)
    amount = value.to_d
    precision = round && amount.frac.zero? ? 0 : 2
    "#{symbol}#{number_with_precision(amount, precision: precision, delimiter: ',', separator: '.')}"
  end

  # Formato liviano para los textos que se editan en el panel:
  #   **texto**  → negrita
  #   ==texto==  → resaltado rojo de la marca
  #   línea vacía → nuevo párrafo
  def rich_text(text, paragraphs: true, klass: nil)
    return "".html_safe if text.blank?
    html = ERB::Util.html_escape(text.to_s.strip)
    html = html.gsub(/\*\*(.+?)\*\*/m, '<strong>\1</strong>')
               .gsub(/==(.+?)==/m, '<span class="mark mark-inline">\1</span>')
    return html.gsub(/\r?\n/, "<br>").html_safe unless paragraphs
    html.split(/\r?\n\s*\r?\n/).map(&:strip).reject(&:blank?)
        .map { |p| content_tag(:p, p.gsub(/\r?\n/, "<br>").html_safe, class: klass) }.join.html_safe
  end

  def inline_text(text) = rich_text(text, paragraphs: false)

  def page_title(*parts)
    [*parts, settings.site_name].compact_blank.join(" | ")
  end

  def upload_url(uploader, version = nil)
    return if uploader.blank?
    version ? uploader.url(version) : uploader.url
  end

  def absolute_url(path)
    return if path.blank?
    path.start_with?("http") ? path : "#{settings.public_base_url}#{path}"
  end

