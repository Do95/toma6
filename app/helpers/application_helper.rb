  # Ilustración de la librería de la marca (ver app/models/illustrations.rb)
  def illustration(key, klass: nil, title: nil)
    return "".html_safe if key.blank?
    Illustrations.svg(key, klass: klass, title: title).html_safe
  end

  def icon(name, size: 18, klass: nil, title: nil)
    paths = ICONS.fetch(name.to_sym) { ICONS[:file] }
    attrs = %(class="icon #{klass}" width="#{size}" height="#{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round")
    label = title ? %( role="img" aria-label="#{ERB::Util.h(title)}") : ' aria-hidden="true"'
    %(<svg #{attrs}#{label}>#{paths}</svg>).html_safe
  end
